import assert from 'node:assert/strict'
import { createPatientDemoData, createPatientsMockService } from './adminPatientsService.js'
import { patientAvatarTone, patientFinancials, patientName, searchPatients, validatePatient } from './adminPatientsModel.js'
import { adminPatientsCopy } from './adminPatientsCopy.js'

const fixtures = createPatientDemoData()
const service = createPatientsMockService(fixtures, { delay: 0 })
const values = { nameEn: '  New Patient  ', nameAr: '\u0645\u0631\u064a\u0636 \u062c\u062f\u064a\u062f', dateOfBirth: '2000-02-29', gender: 'UNKNOWN', phone: ' +9700012345 ', address: '  Demo address  ' }
assert.deepEqual(validatePatient(values), {})
assert.equal(validatePatient({ ...values, nameAr: ' ' }).nameAr, 'required')
assert.equal(validatePatient({ ...values, nameAr: 'ن'.repeat(121) }).nameAr, 'nameLength')
for (const patient of fixtures.patients) {
  assert.match(patientName(patient, 'en'), /^[A-Za-z\s-]+$/)
  assert.match(patientName(patient, 'ar'), /^[\u0600-\u06ff\s]+$/)
  assert.equal(patientAvatarTone(patient.id), patientAvatarTone({ ...patient, gender: 'UNKNOWN' }.id))
}
assert.equal(searchPatients(fixtures.patients, 'لينا ناصر').length, 2)
assert.equal(searchPatients(fixtures.patients, 'Noor Ahmad').length, 1)
assert.equal(searchPatients(fixtures.patients, 'نور أحمد').length, 1)
assert.equal(validatePatient({ ...values, nameEn: ' ' }).nameEn, 'required')
assert.equal(validatePatient({ ...values, phone: ' ' }).phone, 'required')
assert.equal(validatePatient({ ...values, nameEn: 'x'.repeat(121) }).nameEn, 'nameLength')
assert.equal(validatePatient({ ...values, phone: '0'.repeat(21) }).phone, 'phoneLength')
assert.equal(validatePatient({ ...values, dateOfBirth: '2001-02-29' }).dateOfBirth, 'date')
assert.equal(validatePatient({ ...values, dateOfBirth: '2999-01-01' }).dateOfBirth, 'future')
assert.equal(validatePatient({ ...values, gender: 'OTHER' }).gender, 'gender')
assert.equal(searchPatients(fixtures.patients, 'Lina Nasser').length, 2)
assert.equal(searchPatients(fixtures.patients, '0599000111').length, 3)
assert.equal(searchPatients(fixtures.patients, 'p-1001').length, 1)
assert.equal(fixtures.patients[0].fileNumber, 'P-1001')
assert.equal(fixtures.patients[0].id, 'demo-patient-1')
assert.ok(fixtures.patients.every(patient => /^P-\d+$/.test(patient.fileNumber)))
assert.equal(searchPatients(fixtures.patients, 'not-a-patient').length, 0)
const ids = new Set(fixtures.patients.map(patient => patient.id))
assert.equal(ids.size, fixtures.patients.length)
assert.ok(fixtures.orders.every(order => ids.has(order.patientId)))
assert.ok(fixtures.appointments.every(item => ids.has(item.patientId) && (!item.orderId || fixtures.orders.some(order => order.id === item.orderId && order.patientId === item.patientId))))
assert.ok(fixtures.transactions.every(item => fixtures.orders.some(order => order.id === item.orderId)))
assert.deepEqual(patientFinancials(fixtures.patients[0].id, fixtures.orders, fixtures.transactions), { available: true, charges: 330, payments: 130, outstanding: 200 })
assert.equal(patientFinancials(fixtures.patients[2].id, fixtures.orders, fixtures.transactions).available, false)
const created = await service.save(values)
assert.equal(created.fileNumber, 'P-1015')
assert.equal(created.id, 'demo-patient-added-1015')
assert.equal(created.nameEn, 'New Patient')
assert.equal(created.nameAr, values.nameAr.trim())
await assert.rejects(service.save({ ...values, nameAr: '' }))
assert.equal(created.phone, '+9700012345')
assert.equal(created.linkedAccountId, null)
const duplicate = await service.save({ ...values, nameEn: fixtures.patients[0].nameEn, phone: fixtures.patients[0].phone })
assert.notEqual(created.fileNumber, duplicate.fileNumber)
assert.notEqual(duplicate.id, fixtures.patients[0].id)
assert.equal(duplicate.linkedAccountId, null)
const original = fixtures.patients[0]
const edited = await service.save({ ...original, nameEn: 'Updated name', linkedAccountId: 'forged', fileNumber: 'forged', creator: 'forged' }, original.id)
assert.equal(edited.linkedAccountId, original.linkedAccountId)
assert.equal(edited.fileNumber, original.fileNumber)
assert.equal(edited.creator, original.creator)
assert.equal((await service.load()).patients.find(patient => patient.id === fixtures.patients[2].id).nameEn, fixtures.patients[2].nameEn)
await assert.rejects(service.save({ ...values, phone: '' }))
const copy = await service.load()
copy.patients.length = 0
assert.equal((await service.load()).patients.length, fixtures.patients.length + 2)
assert.deepEqual(Object.keys(adminPatientsCopy.en).sort(), Object.keys(adminPatientsCopy.ar).sort())
for (const key of ['errors', 'genders', 'orderStatuses', 'appointmentStatuses']) assert.deepEqual(Object.keys(adminPatientsCopy.en[key]), Object.keys(adminPatientsCopy.ar[key]))
console.log('PASS: validation, duplicate identities, search, generated file numbers, immutable account/system fields, relationship ownership, refunds/confirmed payments, session isolation, and bilingual copy.')
