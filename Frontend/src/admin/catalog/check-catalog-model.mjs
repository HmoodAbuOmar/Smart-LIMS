import assert from 'node:assert/strict'
import { createCatalogData, createCatalogService } from './adminCatalogService.js'
import { applicabilityOverlaps, filterTests, intervalsOverlap, rangeValidity, sortedParameters, validateParameter, validateRange, validateTest } from './adminCatalogModel.js'
import { adminCatalogCopy } from './adminCatalogCopy.js'

const data = createCatalogData(), service = createCatalogService(data, { delay: 0 })
const test = { code: 'NEW', nameEn: 'New panel', nameAr: 'فحص جديد', price: '12.34', sampleType: 'BLOOD', active: true }
assert.deepEqual(validateTest(test, data.tests), {})
for (const [field, value, error] of [['code', '', 'required'], ['code', data.tests[0].code, 'duplicateCode'], ['code', 'a'.repeat(31), 'codeLength'], ['nameAr', 'ن'.repeat(151), 'nameLength'], ['sampleType', 'x'.repeat(41), 'sampleLength'], ['price', '-1', 'price'], ['price', '1.234', 'price'], ['price', '', 'required']]) assert.equal(validateTest({ ...test, [field]: value }, data.tests)[field], error)
assert.equal(filterTests(data.tests, 'تعداد الدم', 'all').length, 1)
assert.equal(filterTests(data.tests, 'Complete Blood', 'all').length, 1)
assert.equal(filterTests(data.tests, '', 'inactive').every(item => !item.active), true)
const savedTest = await service.saveTest(test)
assert.equal(savedTest.priceCents, 1234)
assert.equal(savedTest.sampleType, 'BLOOD')
assert.equal(savedTest.nameAr, test.nameAr)
assert.deepEqual(createCatalogData().tests.map(item => item.id), Array.from({length:12}, (_,i) => `catalog-test-${i+1}`))
assert.deepEqual(createCatalogData().tests.slice(0,8).map(item => item.code), ['CBC','GLU','LIPID','HBA1C','TSH','VITD','CRP','B12'])
assert.ok(createCatalogData().tests.every(item => item.preparationAr === '' && item.preparationEn === ''))
const supplied = structuredClone(data)
supplied.tests[0].nameEn = 'Preserved edit'
supplied.tests.push({...savedTest,id:'custom-patient-independent-test'})
const existing = createCatalogService(supplied,{delay:0})
assert.deepEqual(await existing.load(), supplied)
const history = structuredClone({ orderItems: [{ testId: savedTest.id, priceCents: 1234 }], resultSnapshots: [{ parameterId: 'catalog-parameter-1', unit: 'mg/L', methodEn: 'Optical analysis' }] })
await service.saveTest({ ...test, price: '20' }, savedTest.id)
assert.equal(history.orderItems[0].priceCents, 1234)
assert.equal((await service.load()).tests.find(item => item.id === savedTest.id).priceCents, 2000)
await service.setTestActive(savedTest.id, false)
assert.equal((await service.load()).tests.find(item => item.id === savedTest.id).active, false)
const parameter = { code: 'VALUE', nameEn: 'Value', nameAr: 'القيمة', valueType: 'NUMERIC', unit: 'u/L', methodEn: 'Method', methodAr: 'الطريقة', displayOrder: 0, required: true, active: true }
const first = await service.saveParameter(parameter, savedTest.id)
await assert.rejects(service.saveParameter(parameter, savedTest.id), error => error.fields.code === 'duplicateCode')
const other = await service.saveParameter(parameter, data.tests[1].id)
assert.notEqual(first.id, other.id)
await assert.rejects(service.saveParameter(parameter, data.tests[1].id, first.id), error => error.fields._form === 'missingParent')
assert.equal(validateParameter({ ...parameter, displayOrder: 1.5 }, [], savedTest.id).displayOrder, 'integer')
assert.equal(validateParameter({ ...parameter, displayOrder: -1 }, [], savedTest.id).displayOrder, 'integer')
assert.equal(validateParameter({ ...parameter, valueType: 'INVALID' }, [], savedTest.id).valueType, 'valueType')
const used = data.parameters[0]
for (const field of ['unit', 'methodEn', 'methodAr', 'valueType']) await assert.rejects(service.saveParameter({ ...used, [field]: field === 'valueType' ? 'TEXT' : 'changed' }, used.testId, used.id), error => error.fields[field] === 'usedDefinition')
assert.deepEqual(history.resultSnapshots[0], { parameterId: used.id, unit: used.unit, methodEn: used.methodEn })
assert.deepEqual(sortedParameters([{ id: 'b', displayOrder: 0 }, { id: 'a', displayOrder: 0 }]).map(item => item.id), ['a', 'b'])

// Artificial values exercise interval arithmetic; no clinical thresholds are seeded.
const range = { sex: 'ANY', minAgeDays: '0', maxAgeDays: '10', lower: '1', upper: '2', referenceEn: '', referenceAr: '', validFrom: '2099-01-01', validTo: '2099-02-01' }
assert.deepEqual(validateRange(range, first, []), {})
assert.equal(validateRange({ ...range, lower: '', upper: '' }, first, []).lower, 'referenceRequired')
assert.equal(validateRange({ ...range, referenceEn: 'text' }, first, [])._form, 'numericOnly')
assert.equal(validateRange({ ...range, lower: '3' }, first, []).upper, 'limits')
assert.equal(validateRange({ ...range, minAgeDays: '-1' }, first, []).minAgeDays, 'integer')
assert.equal(validateRange({ ...range, maxAgeDays: '0' }, first, []).maxAgeDays, 'interval')
assert.equal(validateRange({ ...range, validTo: range.validFrom }, first, []).validTo, 'interval')
assert.equal(validateRange({ ...range, validFrom: '2099-02-30' }, first, []).validFrom, 'date')
const r1 = await service.saveRange(range, first.id)
await assert.rejects(service.saveRange({ ...range, minAgeDays: '5', maxAgeDays: '15' }, first.id), error => error.fields._form === 'overlap')
const r2 = await service.saveRange({ ...range, minAgeDays: '10', maxAgeDays: '20' }, first.id)
assert.equal(applicabilityOverlaps(r1, r2), false)
const r3 = await service.saveRange({ ...range, validFrom: range.validTo, validTo: '2099-03-01' }, first.id)
assert.equal(applicabilityOverlaps(r1, r3), false)
assert.equal(intervalsOverlap(null, 0, 0, null), false)
assert.equal(intervalsOverlap(null, null, 0, 1), true)
const unbounded = await service.saveRange({ ...range, sex: 'MALE', minAgeDays: '', maxAgeDays: null, validFrom: null, validTo: '', lower: '0', upper: '' }, first.id)
assert.equal(unbounded.minAgeDays, null); assert.equal(unbounded.maxAgeDays, null); assert.equal(unbounded.lower, 0); assert.equal(unbounded.upper, null)
assert.equal(unbounded.validFrom, null); assert.equal(unbounded.validTo, null)
await assert.rejects(service.saveRange({ ...range, sex: 'MALE', minAgeDays: '', maxAgeDays: '', validFrom: '', validTo: '' }, first.id), error => error.fields._form === 'overlap')
// ANY is distinct from MALE/FEMALE; a different parent is independent too.
await service.saveRange({ ...range, sex: 'FEMALE' }, first.id)
await service.saveRange(range, other.id)
const closed = await service.closeRange(r1.id, '2099-01-20')
assert.deepEqual(closed, { ...r1, validTo: '2099-01-20' })
await assert.rejects(service.closeRange(r1.id, '2098-12-31'), error => error.fields.validTo === 'interval')
await assert.rejects(service.closeRange(r1.id, ''), error => error.fields.validTo === 'required')
assert.equal(rangeValidity({ validFrom: null, validTo: '2026-01-01' }, '2026-01-01'), 'expired')
assert.equal(rangeValidity({ validFrom: '2026-01-02', validTo: null }, '2026-01-01'), 'future')
assert.equal(rangeValidity({ validFrom: null, validTo: null }, '2026-01-01'), 'current')
await assert.rejects(service.saveParameter({ ...first, valueType: 'TEXT' }, savedTest.id, first.id), error => error.fields.valueType === 'hasRanges')
const text = await service.saveParameter({ ...parameter, code: 'TEXT', valueType: 'TEXT' }, savedTest.id)
assert.equal(validateRange(range, text, [])._form, 'textOnly')
await assert.rejects(service.saveRange({ sex: 'ANY' }, text.id), error => Boolean(error.fields.referenceEn))
const textRange = await service.saveRange({ sex: 'ANY', referenceEn: 'Reviewed', referenceAr: 'تمت المراجعة' }, text.id)
assert.equal(textRange.lower, null); assert.equal(textRange.upper, null)
assert.equal((await service.load()).ranges.find(item => item.id === r1.id).id, r1.id)
const isolated = await service.load(); isolated.tests.length = 0
assert.ok((await service.load()).tests.length > 0)
assert.equal(createCatalogData().ranges.length, 0)
assert.deepEqual(Object.keys(adminCatalogCopy.en), Object.keys(adminCatalogCopy.ar))
assert.deepEqual(Object.keys(adminCatalogCopy.en.errors), Object.keys(adminCatalogCopy.ar.errors))
console.log('PASS: catalog validation, bilingual search, scoped unique codes, stable IDs/order, historical definitions, immutable snapshots, type guards, null/zero boundaries, two-dimensional overlap, adjacency, ANY independence, validity closure and bilingual copy.')
