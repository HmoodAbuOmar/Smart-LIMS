import assert from 'node:assert/strict'
import { createTodayData, createTodayService } from './todayDevelopmentService.js'
import { arrivalCounts, canCheckIn, canMarkNoShow, dayAppointments, filterArrivals, formatTime, todayDate } from './todayModel.js'
import { todayService } from './todayService.js'
import { todayCopy } from './todayCopy.js'
const now = () => new Date('2026-11-10T14:00:00Z')
const data = createTodayData(now())
assert.equal(todayDate(new Date('2026-11-09T22:30:00Z')), '2026-11-10')
assert.equal(todayDate(new Date('2026-06-09T21:30:00Z')), '2026-06-10')
const rows = dayAppointments([...data].reverse(), '2026-11-10')
assert.deepEqual(rows, data)
assert.equal(dayAppointments(data, '2026-11-11').length, 0)
assert.deepEqual(arrivalCounts(rows), { arrivals: 7, checkedIn: 1, notArrived: 3 })
assert.equal(filterArrivals(rows, 'arrivals').find(row => row.status === 'NO_SHOW').id, 'r01-appointment-3')
assert.equal(filterArrivals(rows, 'notArrived').length, 3)
assert.equal(canCheckIn(data[0]), true)
assert.equal(canCheckIn(data[6]), false)
assert.equal(canCheckIn(data[1]), false)
const service = createTodayService({ initial: data, now, delay: 0 })
const saved = await service.checkIn(data[0].id, 0)
assert.equal(saved.status, 'CHECKED_IN')
assert.equal(saved.arrivedAt, now().toISOString())
assert.equal(saved.version, 1)
assert.deepEqual(arrivalCounts(await service.load()), { arrivals: 7, checkedIn: 2, notArrived: 2 })
await assert.rejects(service.checkIn(data[0].id, 0), { code: 'APPOINTMENT_CHANGED' })
await assert.rejects(service.checkIn(data[6].id, 0), { code: 'APPOINTMENT_STATE_CONFLICT' })
assert.equal(canMarkNoShow(data[0], new Date(data[0].endsAt)), true)
assert.equal(canMarkNoShow(data[0], new Date(Date.parse(data[0].endsAt) - 1)), false)
assert.equal(canMarkNoShow(saved, now()), false)
const manual = await service.markNoShow(data[3].id, 0)
assert.equal(manual.status, 'NO_SHOW'); assert.equal(manual.arrivedAt, null)
const failure = createTodayService({ initial: data, now, delay: 0, beforeWrite: async () => { throw new Error('offline') } })
await assert.rejects(failure.checkIn(data[0].id, 0))
assert.deepEqual(await failure.load(), data)
const snapshot = await service.load(); snapshot[0].patient.nameEn = 'Changed'
assert.equal((await service.load())[0].patient.nameEn, data[0].patient.nameEn)
assert.deepEqual(await createTodayService({ initial: [], delay: 0 }).load(), [])
assert.equal(formatTime(null, 'en'), '—')
assert.ok(formatTime(now().toISOString(), 'ar'))
assert.deepEqual(Object.keys(todayCopy.en).sort(), Object.keys(todayCopy.ar).sort())
for (const language of ['en', 'ar']) for (const record of data) assert.ok(todayCopy[language][record.status])
await assert.rejects(todayService.load(), { code: 'RECEPTIONIST_UNAVAILABLE' })
await assert.rejects(todayService.checkIn('any-id', 0), { code: 'RECEPTIONIST_UNAVAILABLE' })
console.log('PASS: scheduling timezone/DST, today-only stable sorting, tab counts/NO_SHOW retention, check-in eligibility/version/arrival, immutable failure, manual no-show policy/boundary, isolated snapshots, empty data and production service unavailable.')
