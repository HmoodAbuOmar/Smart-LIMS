import assert from 'node:assert/strict'
import { medicalVisits, measurementSeries, measurementsInRange, numericResult, resultFlag, trendStatistics } from '../src/portal/history/historyModel.js'
const now = new Date('2026-10-26T12:00:00')
const row = { name: ['Hemoglobin', 'Hb'], biomarkerId: 'hemoglobin', value: '12.4', unit: 'g/dL', methodId: 'photometry', specimen: 'blood', reference: { low: 12, high: 16, unit: 'g/dL' } }
const state = { profile: { fileNumber: 'P1' }, orders: [], appointments: [], results: [] }
for (const [index, date] of ['2026-01-01', '2026-06-01', '2026-10-01'].entries()) {
  state.orders.push({ id: `O${index}`, status: 'completed', patientId: 'P1', tests: ['cbc'] })
  state.appointments.push({ id: `A${index}`, orderId: `O${index}`, date, time: '10:00', status: 'completed', patientId: 'P1' })
  state.results.push({ id: `R${index}`, orderId: `O${index}`, appointmentId: `A${index}`, testId: 'cbc', date, measuredAt: `${date}T10:00:00`, verified: true, status: 'published', patientId: 'P1', values: [{ ...row, value: 12 + index }] })
}
let visits = medicalVisits(state, now)
assert.deepEqual(visits.map(v => v.order.id), ['O2', 'O1', 'O0'], 'Most recent first')
assert.equal(medicalVisits({ ...state, appointments: state.appointments.map(a => ({ ...a, status: 'cancelled' })) }, now).length, 0)
assert.equal(medicalVisits({ ...state, appointments: state.appointments.map(a => ({ ...a, status: 'confirmed' })) }, now).length, 0)
assert.equal(medicalVisits({ ...state, results: state.results.map(r => ({ ...r, verified: false })) }, now).length, 0)
assert.equal(medicalVisits({ ...state, results: state.results.map(r => ({ ...r, status: 'pending' })) }, now).length, 0)
assert.equal(medicalVisits({ ...state, results: state.results.map(r => ({ ...r, patientId: 'OTHER' })) }, now).length, 0)
assert.equal(medicalVisits({ ...state, results: state.results.map(r => ({ ...r, patientId: undefined })) }, now).length, 0)
assert.equal(medicalVisits({ ...state, profile: {} }, now).length, 0)
assert.equal(medicalVisits({ ...state, results: state.results.map(r => ({ ...r, appointmentId: 'OTHER' })) }, now).length, 0)
assert.equal(medicalVisits({ ...state, appointments: state.appointments.map(a => ({ ...a, date: '2999-01-01' })) }, now).length, 0)
let series = measurementSeries(visits)
assert.equal(series.length, 1); assert.equal(series[0].points.length, 3)
assert.deepEqual(series[0].points.map(p => p.value), [12, 13, 14])
assert.equal(measurementsInRange(series[0].points, 'months3', now).length, 1)
assert.equal(measurementsInRange(series[0].points, 'months6', now).length, 2)
assert.equal(measurementsInRange(series[0].points, 'year1', now).length, 3)
assert.equal(measurementSeries(visits.map(v => ({ ...v, reports: v.reports.map(r => ({ ...r, measuredAt: undefined })) })), now).length, 0)
assert.equal(measurementsInRange([{ date: '2999-01-01', value: 10 }], 'allTime', now).length, 0)
state.results[0].values.push({ ...row, unit: 'g/L', value: 124 }, { ...row, methodId: 'other-method' }, { ...row, biomarkerId: 'other-biomarker' }, { ...row, specimen: 'other-specimen' }, { ...row, methodId: undefined })
series = measurementSeries(medicalVisits(state, now))
assert.equal(series.length, 5, 'Units, methods, biomarkers and specimen types are separate; unknown methods omitted')
assert.equal(numericResult('<5'), null); assert.equal(numericResult(''), null); assert.equal(numericResult('0'), 0)
assert.equal(resultFlag({ ...row, value: 1000 }), 'high', 'No computed critical threshold')
assert.equal(resultFlag({ ...row, flag: 'critical' }), 'unclassified')
assert.equal(resultFlag({ ...row, flag: 'critical', criticalVerified: true }), 'critical')
assert.equal(resultFlag({ ...row, value: 10 }), 'low')
assert.equal(resultFlag({ ...row, reference: { low: 12, high: 16, unit: 'g/L' } }), 'unclassified')
assert.equal(trendStatistics([{ value: 0 }, { value: 2 }]).percent, null)
assert.equal(trendStatistics([{ value: 10 }, { value: 8 }]).change, -2)
assert.equal(trendStatistics([{ value: 10 }, { value: 8 }]).percent, -20)
assert.equal(trendStatistics([{ value: 10 }]).change, null)
console.log('History model checks passed: completion/publication/verification/ownership/link gating, chronology, compatible series, time ranges, zero-safe changes, and laboratory-defined critical flags.')
